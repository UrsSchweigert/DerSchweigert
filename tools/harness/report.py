"""Publish the run's current state as a markdown page on a branch of the repository.

This module only reads the store, and writes exactly one file to exactly one branch, `harness/status/<plan>`. It never
touches the run branch, the base branch, evidence, or a lease, so it can run beside a live coordinator without changing
what that coordinator decides. A failure here is reported and the next interval tries again.

The page is a plain markdown file on a branch, so GitHub renders it in the repository view with no Pages setup, no
workflow, and no deploy: the status branch matches no push trigger in `.github/workflows`.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import tempfile
import time
from typing import Any, Dict, List, Optional

from . import status
from .publisher import git_with_token

STATUS_BRANCH_PREFIX = "harness/status/"
STATUS_FILE = "STATUS.md"
_BRANCH = re.compile(r"^harness/status/[a-z0-9][a-z0-9._-]{0,80}$")
PUSH_TIMEOUT_S = 120


class StatusRefused(Exception):
    pass


def status_branch(plan_id: str) -> str:
    """The only branch this module may write. Derived from the plan, never taken from free text."""
    slug = re.sub(r"[^a-z0-9._-]+", "-", plan_id.lower()).strip("-")[:80]
    return STATUS_BRANCH_PREFIX + slug


def _checked_branch(branch: str) -> str:
    if not _BRANCH.match(branch):
        raise StatusRefused("the status page is only ever written to %s<plan-id>, not %r" % (STATUS_BRANCH_PREFIX, branch))
    return branch


def redact(text: str) -> str:
    """Nothing on the page may name this machine's home directory or a credential."""
    for value in {os.path.expanduser("~"), os.path.expanduser("~") + "/"}:
        if value.endswith("/"):
            continue
        text = text.replace(value, "~")
    text = re.sub(r"\b(gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,})\b", "<redacted>", text)
    return text


def _age(seconds: Optional[float]) -> str:
    if seconds is None:
        return "-"
    seconds = max(0, int(seconds))
    if seconds < 90:
        return "%ds" % seconds
    if seconds < 5400:
        return "%dm" % (seconds // 60)
    return "%.1fh" % (seconds / 3600.0)


def _pull_requests(report: Dict[str, Any]) -> str:
    numbers = sorted({i["pr"] for i in (report.get("queue") or report.get("issues") or []) if i.get("pr")})
    return "%d opened (%s)" % (len(numbers), ", ".join("#%d" % n for n in numbers[-8:])) if numbers else "none yet"


def page(home: Optional[str], plan_id: str, now: Optional[float] = None) -> str:
    """Render the plan's live state as one markdown page."""
    report = status.filter_plan(status.build_report(home, now), plan_id)
    versions = report.get("plans") or []
    if not versions:
        raise StatusRefused("no plan %r in %s" % (plan_id, report.get("store")))
    plan = max(versions, key=lambda p: p.get("version") or 0)
    stamp = time.strftime("%Y-%m-%d %H:%M:%S %Z", time.localtime(report.get("now") or time.time()))
    runner = report.get("runner") or {}
    issues = report.get("issues") or []
    counts: Dict[str, int] = {}
    for issue in issues:
        counts[issue["state"]] = counts.get(issue["state"], 0) + 1
    order = ["Done", "In Review", "In Progress", "Ready", "Refining", "Blocked", "Cancelled"]
    summary = ", ".join("%s %d" % (s, counts[s]) for s in order if counts.get(s)) or "no issues"

    lines: List[str] = [
        "# %s" % plan_id,
        "",
        "Machine-generated by the harness. Regenerated every few minutes; never merged into any other branch.",
        "",
        "| | |",
        "|---|---|",
        "| Updated | %s |" % stamp,
        "| Plan | v%s, **%s** (digest `%s`) |" % (plan.get("version"), plan.get("state"), plan.get("digest")),
        "| Approval | %s |" % plan.get("approval"),
        "| Base / run branch | `%s` / `%s` |" % (plan.get("base_branch"), plan.get("run_branch")),
        "| Runner | %s (%s), heartbeat %s ago |" % (
            runner.get("status", "unknown"), runner.get("runner_id", "-"), _age(runner.get("last_heartbeat_age_s"))),
        "| Isolation | Tier %s: %s |" % ((report.get("isolation") or {}).get("tier"), (report.get("isolation") or {}).get("reason")),
        "| Issues | %s |" % summary,
        "| Pull requests | %s |" % _pull_requests(report),
    ]
    if plan.get("paused_reason"):
        lines.append("| Paused | %s |" % plan["paused_reason"])

    phases = sorted(report.get("phases") or [], key=lambda p: str(p.get("phase")))
    if phases:
        lines += ["", "## Phases", "", "| Phase | State | Issues |", "|---|---|---|"]
        for ph in phases:
            if ph.get("version") != plan.get("version"):
                continue
            counts_text = ", ".join("%s %d" % (k, v) for k, v in sorted((ph.get("issues") or {}).items()))
            lines.append("| %s | %s | %s |" % (ph.get("phase"), ph.get("state"), counts_text or "-"))

    workers = report.get("workers") or []
    lines += ["", "## Working now", ""]
    if workers:
        lines += ["| Attempt | Issue | Role | Model | Elapsed |", "|---|---|---|---|---|"]
        for w in workers:
            lines.append("| `%s` | %s | %s | `%s` | %s |" % (
                w.get("attempt_id"), w.get("issue"), w.get("role"), w.get("model") or "-", _age(w.get("elapsed_s"))))
    else:
        lines.append("Nothing is running.")

    blockers = report.get("blockers") or []
    tasks = report.get("human_tasks") or []
    if blockers or tasks:
        lines += ["", "## Waiting for the owner", ""]
        for b in blockers:
            lines.append("- **%s** blocked: %s" % (b.get("issue_id"), redact(str(b.get("reason") or "")[:300])))
        for t in tasks:
            lines.append("- task `%s` (%s, %s): %s" % (
                t.get("task_id"), t.get("kind"), t.get("state"), redact(str(t.get("why") or "")[:300])))

    recent = list(report.get("events") or [])[-15:]
    if recent:
        lines += ["", "## Last events", "", "| Time | Event | Issue | Data |", "|---|---|---|---|"]
        for e in recent:
            data = json.dumps(e.get("data") or {}, sort_keys=True)[:160].replace("|", "\\|")
            lines.append("| %s | %s | %s | `%s` |" % (
                time.strftime("%H:%M:%S", time.localtime(e["ts"])), e.get("type"), e.get("issue_id") or "-", data))

    if report.get("usage"):
        lines += ["", "## Usage", "", redact(str(report["usage"])), ""]
    lines += ["", "---", "", "*This branch is written by the harness status publisher and is never merged. "
              "The run's own branch is `%s`.*" % plan.get("run_branch")]
    return redact("\n".join(lines)) + "\n"


def local_copy(home: str, plan_id: str, text: str) -> str:
    """Always keep the current page on disk, so the state is readable even when GitHub is not."""
    target = os.path.join(home, "status-%s.md" % re.sub(r"[^a-z0-9._-]+", "-", plan_id.lower()))
    tmp = target + ".tmp"
    with open(tmp, "w") as fh:
        fh.write(text)
    os.replace(tmp, target)
    return target


def _digest(text: str) -> str:
    """Hash the page without its timestamp line, so an unchanged run does not push every interval."""
    return hashlib.sha256(re.sub(r"^\| Updated \|.*$", "", text, flags=re.M).encode("utf-8")).hexdigest()


def _last_digest(home: str, plan_id: str) -> str:
    try:
        with open(os.path.join(home, "status-%s.json" % plan_id.lower())) as fh:
            return json.load(fh).get("digest", "")
    except (OSError, ValueError):
        return ""


def _remember_digest(home: str, plan_id: str, digest: str, extra: Dict[str, Any]) -> None:
    try:
        with open(os.path.join(home, "status-%s.json" % plan_id.lower()), "w") as fh:
            json.dump(dict(extra, digest=digest), fh)
    except OSError:
        pass


def _remote_tip(remote: str, branch: str, workdir: str, token_file: Optional[str]) -> str:
    proc = git_with_token(["ls-remote", "--heads", remote, "refs/heads/" + branch], workdir, token_file)
    if proc.returncode != 0:
        raise StatusRefused("could not read %s: %s" % (branch, proc.stderr.strip()[-200:]))
    return (proc.stdout.split() or [""])[0]


def publish(text: str, repo: str, branch: str, token_file: Optional[str], message: str) -> str:
    """Write the page as the only commit on the status branch, and return the commit id.

    Force is used with a lease against the tip that exists right now, so a branch somebody else moved is refused rather
    than overwritten, exactly like the worker branches.
    """
    _checked_branch(branch)
    remote = "https://github.com/%s.git" % repo
    work = tempfile.mkdtemp(prefix="harness-status-")
    try:
        steps = [
            ["init", "--quiet"],
            ["checkout", "--quiet", "-b", branch],
            ["add", STATUS_FILE],
            ["-c", "user.name=harness", "-c", "user.email=harness@localhost", "commit", "--quiet", "-m", message],
        ]
        for step in steps[:2]:
            proc = git_with_token(step, work, None)
            if proc.returncode != 0:
                raise StatusRefused("git %s failed: %s" % (step[0], proc.stderr.strip()[-200:]))
        with open(os.path.join(work, STATUS_FILE), "w") as fh:
            fh.write(text)
        for step in steps[2:]:
            proc = git_with_token(step, work, None)
            if proc.returncode != 0:
                raise StatusRefused("git %s failed: %s" % (step[0], proc.stderr.strip()[-200:]))
        tip = _remote_tip(remote, branch, work, token_file)
        push = ["push", "--quiet", remote, "HEAD:refs/heads/%s" % branch]
        if tip:
            push.insert(1, "--force-with-lease=refs/heads/%s:%s" % (branch, tip))
        proc = git_with_token(push, work, token_file)
        if proc.returncode != 0:
            raise StatusRefused("push of %s failed: %s" % (branch, proc.stderr.strip()[-300:]))
        head = git_with_token(["rev-parse", "HEAD"], work, None)
        return head.stdout.strip()
    finally:
        import shutil
        shutil.rmtree(work, ignore_errors=True)


def publish_once(home: Optional[str], plan_id: str, repo: Optional[str], token_file: Optional[str],
                 branch: Optional[str] = None, now: Optional[float] = None, force: bool = False) -> Dict[str, Any]:
    """Render, keep a local copy, and push only when the page changed. Never raises for a publishing problem."""
    out: Dict[str, Any] = {"plan": plan_id, "changed": False, "pushed": False, "branch": "", "path": "", "error": ""}
    try:
        home = home or status.build_report()["store"]
        text = page(home, plan_id, now)
        digest = _digest(text)
        out["path"] = local_copy(home, plan_id, text)
        out["branch"] = _checked_branch(branch or status_branch(plan_id))
        out["changed"] = digest != _last_digest(home, plan_id)
        if not out["changed"] and not force:
            return out
        if not repo:
            _remember_digest(home, plan_id, digest, {"branch": out["branch"]})
            return out
        message = "harness status: %s\n\nGenerated by the harness status publisher. This branch is never merged." % plan_id
        out["commit"] = publish(text, repo, out["branch"], token_file, message)
        out["pushed"] = True
        _remember_digest(home, plan_id, digest, {"branch": out["branch"], "commit": out["commit"]})
        return out
    except Exception as exc:  # noqa: BLE001 - a status page must never break the run or the loop
        out["error"] = "%s: %s" % (type(exc).__name__, str(exc)[:300])
        return out


def watch(home: Optional[str], plan_id: str, repo: Optional[str], token_file: Optional[str], interval: float,
          branch: Optional[str] = None, once: bool = False, emit=None) -> int:
    """Publish on an interval until interrupted. Each pass is independent; an error is reported and the next runs."""
    say = emit or (lambda message: print(message, flush=True))
    while True:
        result = publish_once(home, plan_id, repo, token_file, branch)
        if result["error"]:
            say("status: not published: %s" % result["error"])
        elif result["pushed"]:
            say("status: published %s (%s)" % (result["branch"], result.get("commit", "")[:12]))
        else:
            say("status: unchanged, kept %s" % result["path"])
        if once:
            return 0 if not result["error"] else 1
        time.sleep(max(30.0, interval))
