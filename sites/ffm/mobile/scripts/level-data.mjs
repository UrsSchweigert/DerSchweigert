// Generates the app's bundled level configuration from the private curriculum
// in ../app/level_data.json. The result is build output in www/ and is never
// written into ../static, which deploys to the website.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export const LEVEL_DATA_SOURCE = join(here, '..', '..', 'app', 'level_data.json');
export const TOTAL_LEVELS = 60;

function assertComplete(data) {
  if (!data || !Array.isArray(data.levels)) {
    throw new Error('Level data must contain a levels array');
  }
  if (data.totalLevels !== TOTAL_LEVELS || data.levels.length !== TOTAL_LEVELS) {
    throw new Error(
      `Expected the complete ${TOTAL_LEVELS}-level curriculum, got ${data.levels.length} levels`,
    );
  }
  data.levels.forEach((config, index) => {
    if (config?.level !== index + 1) {
      throw new Error(`Level data is out of order at index ${index}: level ${config?.level}`);
    }
  });
}

/**
 * Renders the level configuration as an ES module for the app bundle.
 * @param {object} data parsed level_data.json
 * @returns {string} module source
 */
export function renderLevelDataModule(data) {
  assertComplete(data);
  const payload = {
    version: data.version,
    generated: data.generated,
    totalLevels: data.totalLevels,
    levels: data.levels,
  };
  return [
    '// Generated by sites/ffm/mobile/scripts/level-data.mjs from',
    '// sites/ffm/app/level_data.json. Do not edit; run copy-assets instead.',
    `export const LEVEL_DATA = Object.freeze(${JSON.stringify(payload, null, 2)});`,
    'export const LevelConfig = LEVEL_DATA.levels;',
    'export const TOTAL_LEVELS = LEVEL_DATA.totalLevels;',
    'export default LEVEL_DATA;',
    '',
  ].join('\n');
}

/**
 * Writes www/game/level-data.js from the private curriculum.
 * @param {string} outFile destination module path
 * @param {string} [sourceFile] level_data.json path
 * @returns {Promise<string>} the written path
 */
export async function generateLevelData(outFile, sourceFile = LEVEL_DATA_SOURCE) {
  const data = JSON.parse(await readFile(sourceFile, 'utf8'));
  const moduleSource = renderLevelDataModule(data);
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, moduleSource);
  return outFile;
}
